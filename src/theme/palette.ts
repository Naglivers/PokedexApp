export type ThemePreference = "system" | "light" | "dark";
export type ColorScheme = "light" | "dark";

export function resolveTheme(
  preference: ThemePreference,
  system: string | null | undefined,
): ColorScheme {
  return preference === "system"
    ? system === "dark"
      ? "dark"
      : "light"
    : preference;
}

